// Aggregates "Couldn't resolve" records (live disk log + observer counts) into one row per card+clause. Pure; scripts/unresolved-report.ts does the IO.
import type { UnresolvedRecord } from "./unresolvedLog";

export interface UnresolvedRow {
  cardName: string;
  clause: string;
  times: number;
  firstSeen: string;
  lastSeen: string;
  decks: string[];
  engines: string[];
  kernelRunnable: "yes" | "no" | "unknown";
}

export function parseUnresolvedJsonl(text: string): UnresolvedRecord[] {
  const out: UnresolvedRecord[] = [];
  for (const line of text.split("\n")) {
    if (!line.trim()) continue;
    try {
      const r = JSON.parse(line) as UnresolvedRecord;
      if (r && typeof r.cardName === "string" && typeof r.clause === "string") out.push(r);
    } catch {
      /* skip a torn line */
    }
  }
  return out;
}

export function aggregateUnresolved(records: UnresolvedRecord[], kernelRunnable: (cardName: string) => "yes" | "no" | "unknown"): UnresolvedRow[] {
  const rows = new Map<string, UnresolvedRow>();
  for (const r of records) {
    const key = `${r.cardName.toLowerCase()}\u0001${r.clause.toLowerCase()}`;
    const row = rows.get(key) ?? { cardName: r.cardName, clause: r.clause, times: 0, firstSeen: r.at, lastSeen: r.at, decks: [], engines: [], kernelRunnable: kernelRunnable(r.cardName) };
    row.times += 1;
    if (r.at < row.firstSeen) row.firstSeen = r.at;
    if (r.at > row.lastSeen) row.lastSeen = r.at;
    for (const d of r.decks ?? []) if (!row.decks.includes(d)) row.decks.push(d);
    if (!row.engines.includes(r.engine)) row.engines.push(r.engine);
    rows.set(key, row);
  }
  return [...rows.values()].sort((a, b) => b.times - a.times || a.cardName.localeCompare(b.cardName));
}

export function renderUnresolvedMarkdown(rows: UnresolvedRow[]): string {
  const esc = (s: string) => s.replace(/\|/g, "/");
  const lines = ["# Unresolved effects (legacy engine / kernel)", "", "Generated by `npm run unresolved:report` from data/observer/live-unresolved.jsonl. Sorted by frequency.", "", "| card | clause | times | first seen | last seen | decks | engine | kernel runnable |", "|---|---|---|---|---|---|---|---|"];
  for (const r of rows) lines.push(`| ${esc(r.cardName)} | ${esc(r.clause)} | ${r.times} | ${r.firstSeen} | ${r.lastSeen} | ${esc(r.decks.join(", "))} | ${r.engines.join(", ")} | ${r.kernelRunnable} |`);
  if (rows.length === 0) lines.push("| (none recorded) | | | | | | | |");
  return `${lines.join("\n")}\n`;
}
