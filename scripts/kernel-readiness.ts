// Writes data/observer/READINESS.md: one "readiness card" per deck (unsupported cards, agreement, remaining diffs by owner, and the deck's complex cards
// with their plain-English re-render ordered by how many diffs involve them). Everything above the marker is generated; the hand-written findings below it are kept.
//   npm run kernel:readiness -- <observer dir> [<observer dir> ...]      (dirs from `npm run kernel:observe`, e.g. data/observer/r3-800)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { cardUnsupported } from "../src/kernel/engine/support";
import { KNOWN_LEGACY } from "../src/kernel/observer/knownLegacy";

const dirs = process.argv.slice(2).filter((a) => !a.startsWith("--"));
if (!dirs.length) { console.error("usage: kernel:readiness -- <observer dir>..."); process.exit(2); }
const out = path.join("data", "observer", "READINESS.md");
const MARK = "<!-- HAND-WRITTEN BELOW: edit freely, the generator keeps everything from this line on -->";
const kept = existsSync(out) ? readFileSync(out, "utf8").split(MARK)[1] ?? "" : "";

const DECKS: Array<{ name: string; slug: string }> = [
  { name: "Wretched Ranks", slug: "wretched-ranks" }, { name: "Tramplesaurus Rex", slug: "tramplesaurus-rex" },
  { name: "Keen Engineering", slug: "keen-engineering" }, { name: "Saheeli", slug: "saheeli" }
];
interface Diff { game: number; actionIndex: number; seed?: number; category: string; cards: string[]; intent: { type: string; label?: string; card?: string }; knownLegacy?: string; seat: string; message: string; repro?: string; field?: string }
interface Stats { agree: number; disagree: number; known: number; skipped: number }

const stats: Record<string, Stats> = {};
const diffs: Array<Diff & { deck?: string }> = [];
for (const d of dirs) {
  const sum = JSON.parse(readFileSync(path.join(d, "summary.json"), "utf8")) as { byDeck: Record<string, Stats> };
  for (const [k, v] of Object.entries(sum.byDeck)) { const s = (stats[k] ??= { agree: 0, disagree: 0, known: 0, skipped: 0 }); s.agree += v.agree; s.disagree += v.disagree; s.known += v.known ?? 0; s.skipped += v.skipped; }
  const lines = readFileSync(path.join(d, "diffs.jsonl"), "utf8").split("\n").filter(Boolean);
  for (const l of lines) { const x = JSON.parse(l) as Diff; diffs.push({ ...x, game: x.game + 1000 * dirs.indexOf(d) }); }
}
const pct = (a: number, b: number): string => (b ? `${((a / b) * 100).toFixed(1)}%` : "n/a");

// one entry per disagreeing action (game + actionIndex), attributed to the acting seat's deck through the repro command's deck order
const byAction = new Map<string, Diff[]>();
for (const d of diffs) { const k = `${d.game}:${d.actionIndex}`; (byAction.get(k) ?? byAction.set(k, []).get(k)!).push(d); }

const L: string[] = ["# Kernel readiness cards", "", `Generated by \`npm run kernel:readiness\` from: ${dirs.map((d) => `\`${d}\``).join(", ")}. Agreement = kernel and legacy engine agree on an action; "excl. known legacy" also counts the actions whose every difference is a documented legacy / harness bug (src/kernel/observer/knownLegacy.ts, listed with evidence below). Hand-written findings follow the generated cards.`, ""];

L.push("## Documented legacy / harness differences (rules the observer uses to classify a difference)", "", "| id | owner | what happens | evidence |", "|---|---|---|---|");
for (const k of KNOWN_LEGACY) L.push(`| ${k.id} | ${k.owner} | ${k.note.replace(/\|/g, "/")} | ${k.evidence.replace(/\|/g, "/")} |`);
L.push("");

for (const deck of DECKS) {
  const idx = JSON.parse(readFileSync(path.join("data", "kernel-drafts", deck.slug, "_index.json"), "utf8")) as { cards: Array<{ slug: string; name: string }> };
  const cardsOfDeck = new Set(idx.cards.map((c) => c.name));
  const unsupported: string[] = [];
  for (const e of idx.cards) {
    const card = JSON.parse(readFileSync(path.join("data", "kernel-drafts", deck.slug, `${e.slug}.json`), "utf8"));
    const s = cardUnsupported({ name: e.name, types: [], kernel: card });
    if (!s.ok) unsupported.push(`${e.name} (${s.all.join(", ")})`);
  }
  const st = stats[deck.name] ?? { agree: 0, disagree: 0, known: 0, skipped: 0 };
  const compared = st.agree + st.disagree;
  L.push(`## ${deck.name}`, "", `- unsupported cards: **${unsupported.length}**${unsupported.length ? ` (${unsupported.join("; ")})` : ""}`, `- agreement: **${pct(st.agree, compared)}** (${st.agree} of ${compared} compared actions); excluding known legacy / harness bugs (${st.known} actions): **${pct(st.agree + st.known, compared)}**`, "");

  // remaining diffs: actions whose acting card belongs to this deck (casts / land plays) or whose diffs name a card of this deck
  const rows = new Map<string, { n: number; owner: string; id: string; example: string }>();
  for (const ds of byAction.values()) {
    const a = ds[0];
    const names = new Set<string>([a.intent.card ?? "", ...ds.flatMap((d) => d.cards)]);
    if (![...names].some((n) => cardsOfDeck.has(n))) continue;
    const known = a.knownLegacy;
    const fields = [...new Set(ds.map((d) => d.category.replace("state_mismatch:", "")))].join("+");
    const label = (a.intent.label ?? a.intent.type).replace(/^cast (commander )?/, "").replace(/ \(X=\d+\)/, "");
    const key = `${known ?? "OPEN"}|${a.intent.type.startsWith("phase") ? a.intent.type : label}`;
    const r = rows.get(key) ?? { n: 0, owner: known ? KNOWN_LEGACY.find((k) => k.id === known)?.owner ?? "?" : "open", id: known ?? "OPEN", example: `${a.repro ?? ""} (action ${a.actionIndex}: ${fields})` };
    r.n++; rows.set(key, r);
  }
  const sorted = [...rows.entries()].sort((a, b) => b[1].n - a[1].n);
  L.push("Remaining differences (actions involving a card of this deck):", "", "| actions | what | classification | example repro |", "|---|---|---|---|");
  for (const [k, v] of sorted.slice(0, 40)) L.push(`| ${v.n} | ${k.split("|")[1]} | ${v.id === "OPEN" ? "OPEN (see findings)" : `${v.id} (${v.owner})`} | \`${v.example.replace(/\|/g, "/")}\` |`);
  L.push("");

  // complex cards for approval, ordered by the number of diff actions that involve them
  const approval = readFileSync(path.join("data", "kernel-drafts", deck.slug, "APPROVAL.md"), "utf8");
  const section = approval.split("## (B) Complex cards")[1] ?? "";
  const blocks = section.split(/\n### /).slice(1).map((b) => { const nl = b.indexOf("\n"); return { name: b.slice(0, nl).trim(), body: b.slice(nl + 1).trim() }; });
  const involved = (name: string): number => { let n = 0; for (const ds of byAction.values()) if (ds[0].intent.card === name || ds.some((d) => d.cards.includes(name))) n++; return n; };
  const ordered = blocks.map((b) => ({ ...b, n: involved(b.name) })).sort((a, b) => b.n - a.n || a.name.localeCompare(b.name));
  L.push(`### ${deck.name}: ${ordered.length} complex cards that need your approval (most diffs first)`, "");
  for (const b of ordered) {
    const rerender = b.body.replace(/^Type:[^\n]*\n+/, "").split("Implementation:")[0];
    L.push(`<details><summary><b>${b.name}</b> - ${b.n} diff action(s)</summary>`, "", rerender.trim().slice(0, 2400), "", "</details>", "");
  }
}
L.push(MARK, kept);
writeFileSync(out, L.join("\n"));
console.log(`wrote ${out}`);
