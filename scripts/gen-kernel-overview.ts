// Writes data/kernel-drafts/OVERVIEW.md: per-deck table + global "kernel needs ranked by number of cards".
// "implemented" = the KERNEL ENGINE (src/kernel/engine/support.ts cardUnsupported) can run the whole card today.
//   npm run kernel:overview     (the hand-written question list at the bottom of the file is preserved)
import Database from "better-sqlite3";
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { complexityOf } from "../src/kernel/deckAudit";
import { cardUnsupported } from "../src/kernel/engine/support";
import type { Card } from "../src/kernel/schema";

const root = path.join("data", "kernel-drafts");
const out = path.join(root, "OVERVIEW.md");
const MARK = "<!-- HAND-WRITTEN BELOW: edit freely, the generator keeps everything from this line on -->";
const kept = existsSync(out) ? readFileSync(out, "utf8").split(MARK)[1] ?? "" : "";
const db = new Database(path.join("data", "cards.db"), { readonly: true, fileMustExist: true });
const stmt = db.prepare("SELECT oracle_text FROM cards WHERE lower(name) = lower(?) OR lower(name) LIKE lower(?) || ' // %' LIMIT 1");

interface Entry { slug: string; name: string; questions?: string[] }
const decks = readdirSync(root).filter((d) => statSync(path.join(root, d)).isDirectory() && existsSync(path.join(root, d, "_index.json"))).sort();
const needCards = new Map<string, Set<string>>(); // need -> card names (global, unique cards)
const seenCard = new Set<string>();
let totalIgnore = 0;
const rows: string[] = [];
let uniqueImpl = 0, uniqueTotal = 0, uniqueComplex = 0;
for (const d of decks) {
  const ix = JSON.parse(readFileSync(path.join(root, d, "_index.json"), "utf8")) as { deck: string; cards: Entry[] };
  let simple = 0, complex = 0, impl = 0, q = 0;
  for (const e of ix.cards) {
    const card = JSON.parse(readFileSync(path.join(root, d, `${e.slug}.json`), "utf8")) as Card;
    const oracle = (stmt.get(e.name, e.name) as { oracle_text: string } | undefined)?.oracle_text ?? card.review?.oracleOverride?.text ?? "";
    const isComplex = complexityOf(oracle).level === "complex" || card.abilities.some((a) => a.scripted) || (e.questions?.length ?? 0) > 0;
    const sup = cardUnsupported({ name: e.name, types: [], kernel: card });
    isComplex ? complex++ : simple++;
    if (sup.ok) impl++;
    q += e.questions?.length ?? 0;
    if (!seenCard.has(e.slug)) {
      seenCard.add(e.slug); uniqueTotal++; if (sup.ok) uniqueImpl++; if (isComplex) uniqueComplex++;
      totalIgnore += card.review?.ignore?.length ?? 0;
      for (const n of sup.all) { const s = needCards.get(n) ?? new Set(); s.add(e.name); needCards.set(n, s); }
    }
  }
  rows.push(`| ${ix.deck} | ${ix.cards.length} | ${simple} | ${complex} | ${impl} | ${ix.cards.length - impl} | ${q} |`);
}
const ranked = [...needCards.entries()].sort((a, b) => b[1].size - a[1].size || a[0].localeCompare(b[0]));
const L: string[] = [];
L.push("# Kernel drafts overview", "", "Generated by `npm run kernel:overview` (do not hand-edit above the marker line). Source: data/kernel-drafts/<deck>/*.json + src/kernel/engine/support.ts.", "");
L.push(`${decks.length} decks, ${uniqueTotal} unique cards (${uniqueComplex} complex, ${uniqueTotal - uniqueComplex} simple). Fully runnable by the kernel engine today: ${uniqueImpl} unique cards. review.ignore entries left across all unique cards: ${totalIgnore}.`, "");
L.push("## Per deck", "", "\"implemented\" = the kernel engine supports every ability of the card; \"needed\" = at least one capability is missing (listed in the ranking below). \"open questions\" = per-card questions recorded in the deck's _index.json (card behaviour AND schema notes).", "");
L.push("| deck | cards | simple | complex | implemented | needed | open questions |", "|---|---|---|---|---|---|---|", ...rows, "");
L.push("## Kernel needs ranked by number of unique cards", "", "Capability names as reported by the engine (`cardUnsupported`). A card appears once per capability it lacks.", "");
L.push("| # cards | capability | example cards |", "|---|---|---|");
for (const [n, cs] of ranked.slice(0, 80)) L.push(`| ${cs.size} | \`${n}\` | ${[...cs].slice(0, 3).join(", ")} |`);
if (ranked.length > 80) L.push(`| | (${ranked.length - 80} more capabilities with fewer cards) | |`);
L.push("", MARK, kept.replace(/^\n/, ""));
writeFileSync(out, L.join("\n") + "\n");
console.log(`wrote ${out}: ${uniqueTotal} cards, ${ranked.length} capabilities, ${totalIgnore} review.ignore left`);
