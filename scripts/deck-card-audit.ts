// Phase 1 audit (TODO_card_parsing.md): lists every unique card in decks/custom + decks/foundations, lifts its parsed_cards row to
// schema v2, runs the kernel validator, and classifies it. Read-only on data/cards.db; writes under bench/coverage/.
//
//   npm run audit:deck-cards
import Database from "better-sqlite3";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { normalizeDeckFile } from "../app/api/decks/library/normalize";
import { parseDeckList } from "../src/lib/deckParser";
import { computeImplementation } from "../src/kernel/capabilities";
import { classifyCard, complexityOf, heuristicFlags, type AuditClass } from "../src/kernel/deckAudit";
import { liftV1Card, type V1Ability } from "../src/kernel/liftV1";
import { generatePrompts } from "../src/kernel/prompts";
import { validateCard } from "../src/kernel/validator";

const OUT = path.join("bench", "coverage");
mkdirSync(OUT, { recursive: true });

// Same filter as app/api/decks/library/route.ts GET, limited to the two shipped folders.
const deckFiles: string[] = [];
for (const dir of ["decks/custom", "decks/foundations"]) {
  for (const f of readdirSync(dir).sort()) if (f.toLowerCase().endsWith(".txt")) deckFiles.push(path.join(dir, f));
}
const decks: Record<string, string[]> = {};
for (const file of deckFiles) {
  const text = readFileSync(file, "utf8");
  const cardLines = text.split(/\r?\n/).filter((l) => /^\d+x?\s+\S/.test(l.trim())).length;
  if (!/^commander:/im.test(text) && cardLines < 30) continue;
  const label = path.basename(file, ".txt");
  const { commander, deckList } = normalizeDeckFile(label, text);
  const parsed = parseDeckList(deckList, commander);
  decks[label] = [...new Set(parsed.cards.map((c) => c.name))];
}
const names = [...new Set(Object.values(decks).flat())].sort((a, b) => a.localeCompare(b));
writeFileSync(path.join(OUT, "deck-cards.json"), JSON.stringify({ deckCount: Object.keys(decks).length, cardCount: names.length, cards: names, decks }, null, 2));

const db = new Database(path.join("data", "cards.db"), { readonly: true, fileMustExist: true });
const cardStmt = db.prepare("SELECT oracle_id, name, type_line, oracle_text FROM cards WHERE lower(name) = lower(?) OR lower(name) LIKE lower(?) || ' // %' ORDER BY (lower(name) = lower(?)) DESC LIMIT 1");
const rowStmt = db.prepare("SELECT parse_status, source, abilities, error FROM parsed_cards WHERE oracle_id = ?");

interface Result {
  name: string; cls: AuditClass; rowStatus: string; source: string; issueCodes: string[]; warnings: string[];
  heuristics: string[]; declinedAbilities: number; complexity: "simple" | "complex"; tags: string[]; decks: string[]; oracleMissing: boolean;
}
const results: Result[] = [];
for (const name of names) {
  const card = cardStmt.get(name, name, name) as { oracle_id: string; type_line: string; oracle_text: string } | undefined;
  const oracle = card?.oracle_text ?? "";
  const row = card ? (rowStmt.get(card.oracle_id) as { parse_status: string; source: string; abilities: string; error: string | null } | undefined) : undefined;
  let validatorOk: boolean | undefined;
  let issueCodes: string[] = [];
  let warnings: string[] = [];
  let declinedAbilities = 0;
  if (row?.parse_status === "ok") {
    let abilities: V1Ability[] = [];
    try { abilities = JSON.parse(row.abilities) as V1Ability[]; } catch { /* leave empty; validator will flag */ }
    declinedAbilities = abilities.filter((a) => a.declined).length;
    try {
      const lifted = computeImplementation(generatePrompts(liftV1Card(abilities), name));
      const res = validateCard(lifted, oracle, name);
      validatorOk = res.ok;
      issueCodes = [...new Set(res.issues.filter((i) => i.severity === "error").map((i) => i.code))];
      warnings = [...new Set(res.issues.filter((i) => i.severity === "warning").map((i) => i.code))];
    } catch (e) {
      validatorOk = false;
      issueCodes = ["AUDIT_EXCEPTION"];
      warnings = [String((e as Error).message).slice(0, 80)];
    }
  }
  const cls = classifyCard({ rowStatus: row?.parse_status, validatorOk });
  const cx = complexityOf(oracle);
  results.push({
    name, cls, rowStatus: row?.parse_status ?? "none", source: row?.source ?? "", issueCodes, warnings,
    heuristics: row?.parse_status === "ok" ? heuristicFlags(oracle) : [], declinedAbilities,
    complexity: cx.level, tags: cx.tags, decks: Object.keys(decks).filter((d) => decks[d].includes(name)), oracleMissing: !card
  });
}

const CLASSES: AuditClass[] = ["verified-candidate", "suspect", "declined", "failed", "missing"];
const count = (rs: Result[], c: AuditClass) => rs.filter((r) => r.cls === c).length;
const lines: string[] = [];
lines.push("# Deck card audit (Phase 1)", "", `${names.length} unique cards across ${Object.keys(decks).length} decks. Generated by \`npm run audit:deck-cards\`.`, "");
lines.push("## Summary", "", "| class | count |", "|---|---|");
for (const c of CLASSES) lines.push(`| ${c} | ${count(results, c)} |`);
lines.push(`| **total** | ${results.length} |`, "");
lines.push(`Cards with no oracle text in the cards table: ${results.filter((r) => r.oracleMissing).length}. ok rows with per-ability declined: ${results.filter((r) => r.declinedAbilities).length}. ok rows with heuristic words: ${results.filter((r) => r.heuristics.length).length}.`, "");

lines.push("## Complexity (how many need manual approval)", "", "| complexity | total | " + CLASSES.join(" | ") + " |", "|---|---|" + CLASSES.map(() => "---").join("|") + "|");
for (const lvl of ["simple", "complex"] as const) {
  const rs = results.filter((r) => r.complexity === lvl);
  lines.push(`| ${lvl} | ${rs.length} | ${CLASSES.map((c) => count(rs, c)).join(" | ")} |`);
}
const tagCounts = new Map<string, number>();
for (const r of results) for (const t of r.tags) tagCounts.set(t, (tagCounts.get(t) ?? 0) + 1);
lines.push("", "Complexity tags (a card can have several): " + [...tagCounts].sort((a, b) => b[1] - a[1]).map(([t, n]) => `${t} ${n}`).join(", "), "");

lines.push("## Per deck", "", "| deck | cards | " + CLASSES.join(" | ") + " |", "|---|---|" + CLASSES.map(() => "---").join("|") + "|");
for (const d of Object.keys(decks)) {
  const rs = results.filter((r) => r.decks.includes(d));
  lines.push(`| ${d} | ${rs.length} | ${CLASSES.map((c) => count(rs, c)).join(" | ")} |`);
}
const codeCounts = new Map<string, number>();
for (const r of results) for (const c of r.issueCodes) codeCounts.set(c, (codeCounts.get(c) ?? 0) + 1);
lines.push("", "## Top validator issue codes (cards affected)", "", "| code | cards |", "|---|---|");
for (const [c, n] of [...codeCounts].sort((a, b) => b[1] - a[1])) lines.push(`| ${c} | ${n} |`);
lines.push("", "## Cards by class", "");
for (const c of CLASSES) {
  lines.push(`### ${c} (${count(results, c)})`, "");
  for (const r of results.filter((x) => x.cls === c)) {
    const extra = [
      r.issueCodes.length ? `issues: ${r.issueCodes.join(", ")}` : "",
      r.declinedAbilities ? `declined abilities: ${r.declinedAbilities}` : "",
      r.heuristics.length ? `words: ${r.heuristics.join("/")}` : "",
      `${r.complexity}${r.tags.length ? ` (${r.tags.join(", ")})` : ""}`
    ].filter(Boolean).join("; ");
    lines.push(`- ${r.name} - ${extra}`);
  }
  lines.push("");
}
writeFileSync(path.join(OUT, "deck-card-audit.md"), lines.join("\n"));

const q = (s: string) => `"${s.replace(/"/g, '""')}"`;
const csv = ["name,class,row_status,source,complexity,complexity_tags,issue_codes,heuristic_words,declined_abilities,decks"];
for (const r of results) csv.push([q(r.name), r.cls, r.rowStatus, q(r.source), r.complexity, q(r.tags.join("|")), q(r.issueCodes.join("|")), q(r.heuristics.join("|")), r.declinedAbilities, q(r.decks.join("|"))].join(","));
writeFileSync(path.join(OUT, "deck-card-audit.csv"), csv.join("\n") + "\n");

console.log(`cards ${names.length}, decks ${Object.keys(decks).length}`);
for (const c of CLASSES) console.log(c, count(results, c));
console.log("simple", results.filter((r) => r.complexity === "simple").length, "complex", results.filter((r) => r.complexity === "complex").length);
console.log("top codes", [...codeCounts].sort((a, b) => b[1] - a[1]).slice(0, 8));
